/*
 * gen-assets.mjs — generate src/assets.generated.ts, which embeds every ETA
 * template and Python script as a string so esbuild bundles them into main.js.
 * The plugin extracts them into its folder on load (extractBundledAssets), so a
 * GitHub release ships everything in the three assets BRAT downloads — no
 * separate templates/ or scripts/ folder needed, and a plugin update carries the
 * new templates, whose changed hashes trigger the scoped re-render.
 *
 * Run automatically before dev/build/check-types (see package.json).
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from "fs";
import { join } from "path";

const GROUPS = [
	{ dir: "midad-arabic-sources-import-templates", exts: [".eta.md", ".json"] },
	{ dir: "scripts", exts: [".py"] },
];

const assets = [];
for (const g of GROUPS) {
	for (const name of readdirSync(g.dir).sort()) {
		const full = join(g.dir, name);
		if (!statSync(full).isFile()) continue;
		if (!g.exts.some((e) => name.endsWith(e))) continue;
		assets.push({ path: `${g.dir}/${name}`, content: readFileSync(full, "utf8") });
	}
}

const lines = [
	"// AUTO-GENERATED by gen-assets.mjs — do not edit by hand.",
	"// Embeds the ETA templates and Python scripts so a release ships them inside",
	"// main.js; the plugin extracts them into its folder on load.",
	"",
	"export interface BundledAsset {",
	"\t/** Path relative to the plugin folder. */",
	"\tpath: string;",
	"\tcontent: string;",
	"}",
	"",
	"export const BUNDLED_ASSETS: BundledAsset[] = [",
];
for (const a of assets) {
	lines.push(`\t{ path: ${JSON.stringify(a.path)}, content: ${JSON.stringify(a.content)} },`);
}
lines.push("];", "");

writeFileSync(join("src", "assets.generated.ts"), lines.join("\n"));
console.log(`gen-assets: bundled ${assets.length} asset(s) into src/assets.generated.ts`);
