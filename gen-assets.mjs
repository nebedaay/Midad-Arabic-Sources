/*
 * gen-assets.mjs — generate src/assets.generated.ts, which embeds every ETA
 * template, Python script, and user-facing doc page as a string so esbuild
 * bundles them into main.js. The plugin extracts the templates and scripts into
 * its folder on load (extractBundledAssets), so a GitHub release ships
 * everything in the three assets BRAT downloads — no separate templates/ or
 * scripts/ folder needed, and a plugin update carries the new templates, whose
 * changed hashes trigger the scoped re-render. The README and docs/*.md are
 * bundled but not extracted: they are read from the bundle by the in-app
 * Documentation modal (src/docs.ts).
 *
 * Run automatically before dev/build/check-types (see package.json).
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from "fs";
import { join } from "path";

const GROUPS = [
	{ dir: "midad-arabic-sources-import-templates", exts: [".eta.md", ".json"] },
	{ dir: "scripts", exts: [".py"] },
	// User-facing docs — bundled so the in-app Documentation modal (src/docs.ts)
	// can render them. Not extracted into the plugin folder (they are read from
	// the bundle).
	{ dir: "docs", exts: [".md"], extract: false },
	// The README is rendered as the docs "Overview" page; also not extracted.
	{ file: "README.md", path: "README.md", extract: false },
];

const assets = [];
for (const g of GROUPS) {
	if (g.file) {
		assets.push({ path: g.path, content: readFileSync(g.file, "utf8"), extract: g.extract });
		continue;
	}
	for (const name of readdirSync(g.dir).sort()) {
		const full = join(g.dir, name);
		if (!statSync(full).isFile()) continue;
		if (!g.exts.some((e) => name.endsWith(e))) continue;
		assets.push({ path: `${g.dir}/${name}`, content: readFileSync(full, "utf8"), extract: g.extract });
	}
}

const lines = [
	"// AUTO-GENERATED by gen-assets.mjs — do not edit by hand.",
	"// Embeds the ETA templates, Python scripts, and doc pages so a release ships",
	"// them inside main.js; the plugin extracts the templates and scripts into its",
	"// folder on load and renders the docs from the bundle.",
	"",
	"export interface BundledAsset {",
	"\t/** Path relative to the plugin folder. */",
	"\tpath: string;",
	"\tcontent: string;",
	"\t/** When false, bundle the asset but do not write it into the plugin folder. */",
	"\textract?: boolean;",
	"}",
	"",
	"export const BUNDLED_ASSETS: BundledAsset[] = [",
];
for (const a of assets) {
	const extract = a.extract === false ? ", extract: false" : "";
	lines.push(`\t{ path: ${JSON.stringify(a.path)}, content: ${JSON.stringify(a.content)}${extract} },`);
}
lines.push("];", "");

writeFileSync(join("src", "assets.generated.ts"), lines.join("\n"));
console.log(`gen-assets: bundled ${assets.length} asset(s) into src/assets.generated.ts`);
